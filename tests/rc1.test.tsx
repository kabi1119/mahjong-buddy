import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { IDBFactory } from 'fake-indexeddb'
import App from '../src/App'
import { loadSettings, saveSettings } from '../src/storage/settings'
import type { Settings } from '../src/storage/settings'
import { createMatch, syncMatch } from '../src/features/match/engine'
import { defaultPreferences, defaultRiichi } from '../src/features/match/rules'
import { newSetup, updateSetup } from '../src/features/game/setup'
import { projectRound, recordAction } from '../src/features/actions/engine'
import { POSITIONS } from '../src/types/mahjong'
import { call, fourPlayers, newGame } from './handFixtures'
const ready = updateSetup(updateSetup(newSetup(), { type: 'dealer', position: 'bottom' }), { type: 'confirm-dealer' })
const playing = updateSetup(updateSetup(ready, { type: 'rolled', dice: [1, 1] }), { type: 'dealt' })
const saved = () => screen.findByText('設定已於此瀏覽器自動儲存')
function matchSettings(): Settings { const data = newGame('riichi'); return { variant: 'riichi', players: fourPlayers, setup: playing, preferences: defaultPreferences(), gameplay: { ...data, match: createMatch(data, defaultRiichi(), false) } } }
beforeEach(() => { vi.stubGlobal('indexedDB', new IDBFactory()); localStorage.clear() })
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals() })
describe('RC1 settings, themes and reset safety', () => {
  it('disables future modes and exposes settings even with no players', async () => {
    render(<App />); await saved()
    const modes = within(screen.getByRole('group', { name: '麻雀模式' })).getAllByRole('button') as HTMLButtonElement[]
    expect(modes.map((mode) => mode.textContent?.trim())).toEqual(['香港麻雀', '日本四麻', '日本三麻Coming soon敬請期待', '台灣麻將Coming soon敬請期待'])
    expect(modes.map((mode) => mode.disabled)).toEqual([false, false, true, true])
    fireEvent.click(modes[2]); expect((await loadSettings()).variant).toBe('hong-kong')
    fireEvent.click(screen.getByRole('button', { name: '牌局設定' }))
    expect(screen.getByLabelText('最低番數')).toHaveProperty('value', '3')
    fireEvent.change(screen.getByLabelText('最低番數'), { target: { value: '5' } })
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect((await loadSettings()).preferences).toBeUndefined()
  })
  it('persists independent rule drafts and cancels restored defaults', async () => {
    render(<App />); await saved()
    fireEvent.click(screen.getByRole('button', { name: '牌局設定' }))
    fireEvent.change(screen.getByLabelText('最低番數'), { target: { value: '5' } })
    fireEvent.click(screen.getByRole('button', { name: '儲存設定' })); await saved()
    expect((await loadSettings()).preferences).toMatchObject({ hongKong: { minimumFan: 5 }, riichi: { startingPoints: 25000 } })
    fireEvent.click(screen.getByRole('button', { name: '牌局設定' }))
    fireEvent.click(screen.getByRole('button', { name: '還原預設' }))
    fireEvent.click(screen.getByRole('button', { name: '取消還原' }))
    expect(screen.getByLabelText('最低番數')).toHaveProperty('value', '5')
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
  })
  it('follows OS changes, persists a manual override, reloads and restores system', async () => {
    const media = new EventTarget() as EventTarget & { matches: boolean }
    media.matches = true; vi.stubGlobal('matchMedia', () => media)
    const app = render(<App />); await saved()
    expect(screen.getByRole('switch').getAttribute('aria-checked')).toBe('true')
    fireEvent.click(screen.getByRole('switch')); await saved()
    expect((await loadSettings()).themePreference).toBe('light')
    act(() => media.dispatchEvent(new Event('change')))
    expect(document.documentElement.dataset.theme).toBe('light')
    app.unmount(); render(<App />); await saved()
    expect(screen.getByRole('switch').getAttribute('aria-checked')).toBe('false')
    fireEvent.click(screen.getByRole('button', { name: '牌局設定' }))
    fireEvent.change(screen.getByLabelText('外觀'), { target: { value: 'system' } }); await saved()
    expect(document.documentElement.dataset.theme).toBe('dark')
    act(() => { media.matches = false; media.dispatchEvent(new Event('change')) })
    expect(document.documentElement.dataset.theme).toBe('light')
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect((await loadSettings()).themePreference).toBe('system')
  })
  it('confirms each distinct reset and preserves rules/history', async () => {
    const settings = matchSettings(); await saveSettings(settings)
    render(<App />); await saved()
    fireEvent.click(screen.getByRole('button', { name: '重設開局（保留牌友）' }))
    expect((await loadSettings()).setup).toEqual(playing)
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect((await loadSettings()).gameplay?.activeRoundId).toBe('round-a')
    fireEvent.click(screen.getByRole('button', { name: '重設開局（保留牌友）' }))
    fireEvent(screen.getByRole('dialog'), new Event('cancel', { cancelable: true }))
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '重設開局（保留牌友）' }))
    fireEvent.click(screen.getByRole('button', { name: '確認重設' })); await saved()
    expect((await loadSettings()).players).toEqual(fourPlayers)
    fireEvent.click(document.querySelector('details summary')!)
    fireEvent.click(screen.getByRole('button', { name: '清除牌友並重設' }))
    expect((await loadSettings()).players).toEqual(fourPlayers)
    fireEvent.click(screen.getByRole('button', { name: '確認清除' })); await saved()
    const stored = await loadSettings()
    expect(stored.players).toEqual({}); expect(stored.preferences).toEqual(settings.preferences)
    expect(stored.gameplay?.pastMatches).toHaveLength(1)
    expect(stored.gameplay?.rounds[0].status).toBe('archived')
  })
})
describe('RC1 round interactions', () => {
  it('requires all four tenpai decisions, finalizes once, reloads and undoes', async () => {
    await saveSettings(matchSettings()); const app = render(<App />); await saved()
    fireEvent.click(screen.getByRole('button', { name: '流局' }))
    fireEvent.click(screen.getByRole('checkbox', { name: /已與四位玩家/ }))
    expect(screen.getByRole('button', { name: '確認流局' })).toHaveProperty('disabled', true)
    const groups = document.querySelectorAll('fieldset.tenpai-player')
    groups.forEach((group, index) => fireEvent.click(within(group as HTMLElement).getByRole('radio', { name: index === 0 ? '聽牌 (Tenpai)' : /未聽牌/ })))
    fireEvent.click(screen.getByRole('checkbox', { name: /已與四位玩家/ }))
    fireEvent.click(screen.getByRole('button', { name: '確認流局' })); await saved()
    expect(screen.getByRole('dialog', { name: '牌局摘要與記錄' })).toBeTruthy()
    const drawn = await loadSettings(); expect(drawn.gameplay?.match).toMatchObject({ honba: 1, kyoku: 2, dealer: 'right', points: { top: 28000, bottom: 24000 } })
    app.unmount(); render(<App />); await saved()
    fireEvent.click(screen.getByRole('button', { name: '查看流局結果及準備下一局' }))
    fireEvent.click(screen.getByRole('button', { name: '撤回最近流局' })); await saved()
    expect((await loadSettings()).gameplay?.match).toMatchObject({ honba: 0, dealer: 'bottom', points: { top: 25000, bottom: 25000 } })
  })
  it('keeps four-Kan timing pending across reload and blocks a win override', async () => {
    const settings = matchSettings(); let data = settings.gameplay!
    for (let index = 0; index < 4; index++) data = recordAction(data, index < 2 ? 'bottom' : 'right', call(index === 3 ? 'daiminkan' : 'ankan', (['1m', '2m', '3m', '4m'] as const)[index], 'kan-' + index))
    settings.gameplay = syncMatch(data); await saveSettings(settings)
    const app = render(<App />); await saved()
    expect(screen.getByRole('dialog', { name: '偵測到四槓散了條件' })).toBeTruthy()
    expect(screen.getByRole('button', { name: '確認四槓散了' })).toHaveProperty('disabled', true)
    fireEvent.click(screen.getByRole('button', { name: '尚未完成／返回牌局' })); await saved()
    app.unmount(); render(<App />); await saved()
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: /四槓散了條件 ·/ }))
    fireEvent.click(screen.getByRole('button', { name: '有人和牌' })); await saved()
    expect((await loadSettings()).gameplay?.match).toMatchObject({ honba: 0, winPending: true, pendingFourKan: { status: 'win-pending' } })
    expect(screen.getByRole('button', { name: '確認四槓散了' })).toHaveProperty('disabled', true)
  })
  it('records a physically confirmed illustrated Chi with source, red composition and undo', async () => {
    await saveSettings(matchSettings()); render(<App />); await saved()
    fireEvent.click(screen.getByRole('button', { name: '開啟動作選單：下方玩家：bottom' }))
    fireEvent.click(screen.getByRole('button', { name: '吃' }))
    expect(screen.queryByRole('button', { name: '字牌' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '索' })); fireEvent.click(screen.getByRole('button', { name: '五索' }))
    expect(document.querySelectorAll('.chi-options button')).toHaveLength(3)
    expect(document.querySelectorAll('.claimed-tile svg')).toHaveLength(3)
    fireEvent.click(screen.getByRole('button', { name: '三索、四索、五索' }))
    fireEvent.change(screen.getByLabelText('順子赤五'), { target: { value: '2' } })
    expect(screen.getByRole('button', { name: '確認記錄順子' })).toHaveProperty('disabled', true)
    fireEvent.click(screen.getByRole('checkbox', { name: /我手中確實/ })); fireEvent.click(screen.getByRole('button', { name: '確認記錄順子' })); await saved()
    const stored = await loadSettings(); const meld = projectRound(stored.gameplay!, 'round-a').melds[0]
    expect(meld).toMatchObject({ kind: 'chi', sourcePlayer: 'left', claimedTile: '5s', suppliedTiles: ['3s', '4s'], redCount: 1 })
    expect(meld.tiles[2].red).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: '開啟動作選單：下方玩家：bottom' })); fireEvent.click(screen.getByText('動作記錄與更正')); fireEvent.click(screen.getByRole('button', { name: '撤回' })); await saved()
    expect(projectRound((await loadSettings()).gameplay!, 'round-a').melds).toHaveLength(0)
  })
  it('does not charge a legacy declaration and asks for explicit baseline values', async () => {
    const data = recordAction(newGame('riichi'), 'bottom', { kind: 'riichi', confirmed: true }, 'legacy')
    await saveSettings({ variant: 'riichi', players: fourPlayers, setup: playing, gameplay: data })
    render(<App />); await saved(); fireEvent.click(screen.getByRole('button', { name: '流局' })); await saved()
    expect(screen.getByRole('heading', { name: '舊立直局尚未對帳' })).toBeTruthy()
    for (const seat of POSITIONS) fireEvent.change(screen.getByLabelText(seat + '實際點數'), { target: { value: seat === 'bottom' ? '24000' : '25000' } })
    fireEvent.change(screen.getByLabelText('實際供託'), { target: { value: '1000' } })
    fireEvent.click(screen.getByRole('checkbox', { name: '確認以上是目前實際數值' })); fireEvent.click(screen.getByRole('button', { name: '確認對帳基準' })); await saved()
    await waitFor(async () => expect((await loadSettings()).gameplay?.match).toMatchObject({ legacyUnreconciled: false, pool: 1000, points: { bottom: 24000 } }))
  })
})
